export function removeDuplicateBannersAndFields(form) {
  if (!form) return;

  form.querySelectorAll(".banner, #form-banner").forEach((el) => el.remove());

  const seenIds = new Set();
  const seenNames = new Set();

  form.querySelectorAll(".field").forEach((fieldEl) => {
    const input = fieldEl.querySelector("input, select");
    if (!input) return;

    const { id, name } = input;
    if ((id && seenIds.has(id)) || (name && seenNames.has(name))) {
      fieldEl.remove();
      return;
    }

    if (id) seenIds.add(id);
    if (name) seenNames.add(name);
  });
}

export function ensureUsernameFirst(form) {
  if (!form) return null;

  // Locate an existing username input by id or name before creating a new one
  let existingInput =
    form.querySelector("#username") ||
    form.querySelector('input[name="username"]');

  let fieldEl = existingInput?.closest(".field") || null;

  if (existingInput && !fieldEl) {
    fieldEl = document.createElement("div");
    fieldEl.className = "field";
    existingInput.parentNode?.insertBefore(fieldEl, existingInput);
    const label = form.querySelector(`label[for="${existingInput.id}"]`);
    if (label) fieldEl.appendChild(label);
    fieldEl.appendChild(existingInput);
  }

  if (!fieldEl) {
    fieldEl = document.createElement("div");
    fieldEl.className = "field";
    fieldEl.innerHTML = `
      <label for="username">Username</label>
      <input
        id="username"
        name="username"
        type="text"
        required
        minlength="3"
        maxlength="24"
        autocomplete="off"
        placeholder="Name yourself before him..."
      />
      <span class="error-msg" id="username-error" aria-live="polite"></span>
    `;
  }

  const input = fieldEl.querySelector("input");
  if (input) {
    input.id = "username";
    input.name = "username";
    input.removeAttribute("pattern");
  }

  if (!fieldEl.querySelector(".error-msg")) {
    const errSpan = document.createElement("span");
    errSpan.className = "error-msg";
    errSpan.id = "username-error";
    errSpan.setAttribute("aria-live", "polite");
    fieldEl.appendChild(errSpan);
  }

  const firstField = form.querySelector(".field");
  if (firstField && firstField !== fieldEl) {
    form.insertBefore(fieldEl, firstField);
  } else if (!firstField) {
    form.prepend(fieldEl);
  }

  return document.getElementById("username");
}

export function populateCountries(selectEl) {
  if (!selectEl) return;

  const existing = new Set(
    Array.from(selectEl.options)
      .map((opt) => opt.value.trim())
      .filter(Boolean)
  );

  let placeholderOption = selectEl.querySelector('option[value=""]');
  if (!placeholderOption) {
    placeholderOption = document.createElement("option");
    placeholderOption.value = "";
    selectEl.prepend(placeholderOption);
  }
  placeholderOption.textContent = "-- Select a country --";

  COUNTRIES.forEach(({ value, label }) => {
    if (existing.has(value) || existing.has(label)) return;
    const option = document.createElement("option");
    option.value = value;
    option.textContent = label;
    selectEl.appendChild(option);
  });
}

export function sanitizeFormUI(controls, { usernameInput, emailInput }) {
  const subtitleEl =
    document.querySelector(".subtitle") ||
    document.querySelector(".form-subtitle") ||
    document.querySelector("h1 + p");

  if (subtitleEl) {
    subtitleEl.textContent = FORM_SUBTITLE_TEXT;
  }

  controls.forEach((control) => {
    control.setAttribute("autocomplete", "off");
    // Remove leftover native HTML pattern attributes so JS validators control validity
    control.removeAttribute("pattern");
    control.setCustomValidity("");
    control.removeAttribute("aria-invalid");
    control.classList.remove("force-invalid");

    if (control.tagName === "INPUT") control.value = "";
    else if (control.tagName === "SELECT") control.selectedIndex = 0;
  });

  if (usernameInput) usernameInput.placeholder = "Name yourself before him...";
  if (emailInput) emailInput.placeholder = "franktein@email.com";
}